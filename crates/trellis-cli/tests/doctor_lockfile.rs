//! `trellis doctor`'s `lockfile:` line (ADR 0057, #779), through the real
//! binary: when it appears, and what it says when the tool is not there.
//!
//! What cargo-audit reports is covered by the unit tests on the parser and
//! the renderer in `doctor_supply.rs`; nothing here fetches an advisory
//! database or needs cargo-audit installed.

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

/// A git repository with one Python file, so `doctor` has an index to
/// report and the line under test is the only thing that varies.
fn repo(name: &str) -> PathBuf {
    let d = std::env::temp_dir().join(format!("trellis-lockfile-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    let out = trellis_vcs::command()
        .args(["init", "-q"])
        .current_dir(&d)
        .output()
        .expect("git on PATH");
    assert!(out.status.success());
    std::fs::create_dir_all(d.join("app")).unwrap();
    std::fs::write(d.join("app/util.py"), "def helper():\n    return 1\n").unwrap();
    d
}

/// `trellis doctor` in `root` with `path` as the child's PATH: an empty
/// directory makes every tool absent, cargo-audit among them.
fn doctor(root: &Path, path: &Path) -> Output {
    let user = std::env::temp_dir().join("trellis-lockfile-no-user-config");
    Command::new(env!("CARGO_BIN_EXE_trellis"))
        .arg("--root")
        .arg(root)
        .arg("doctor")
        .current_dir(root)
        .env("NO_COLOR", "1")
        .env("TRELLIS_CONFIG_DIR", &user)
        .env("PATH", path)
        .env_remove("OPENAI_API_KEY")
        .env_remove("ANTHROPIC_API_KEY")
        .output()
        .expect("the binary is built")
}

fn stdout(o: &Output) -> String {
    let s = String::from_utf8_lossy(&o.stdout).into_owned();
    assert!(
        o.status.success(),
        "doctor failed: {s}\n{}",
        String::from_utf8_lossy(&o.stderr)
    );
    s
}

#[test]
fn a_repository_without_a_lockfile_gets_no_lockfile_line() {
    // The risk: a Python repository, which is what trellis is pointed at,
    // reading `lockfile: not applicable` on every doctor and learning to
    // skip the column (ADR 0057 decision 1).
    let d = repo("none");
    let empty = d.join("empty-path");
    std::fs::create_dir_all(&empty).unwrap();
    let s = stdout(&doctor(&d, &empty));
    assert!(
        !s.lines().any(|l| l.starts_with("lockfile:")),
        "a `lockfile:` line with no Cargo.lock:\n{s}"
    );
}

#[test]
fn a_lockfile_with_no_cargo_audit_on_path_reads_not_checked_and_names_the_tool() {
    // The risk: silence, or `clean`, when the tool that would have said
    // otherwise is not installed. The line must say the check did not
    // happen and where the answer is (CI's commands).
    let d = repo("absent");
    std::fs::write(
        d.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\nversion = 4\n",
    )
    .unwrap();
    let empty = d.join("empty-path");
    std::fs::create_dir_all(&empty).unwrap();
    let s = stdout(&doctor(&d, &empty));
    let line = s
        .lines()
        .find(|l| l.starts_with("lockfile:"))
        .unwrap_or_else(|| panic!("no `lockfile:` line in:\n{s}"));
    assert!(
        line.contains("not checked") && line.contains("cargo-audit is not on PATH"),
        "{line}"
    );
    assert!(!line.contains("clean"), "{line}");
    assert!(s.contains("cargo deny --locked check"), "{s}");
}
